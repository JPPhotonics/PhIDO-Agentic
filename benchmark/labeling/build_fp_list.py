"""Render all DIA false positives (DIA-approved edges experts labelled not_supported)
across the 5-annotator A2 round, with evidence quotes, for improvement-E design.
Join: labels_*.json (expert label + shown_order) x bundles/labeler_*.html (const BUNDLE:
head/tail/types/quotes, keyed by shown_order) x bundles/bundle_meta_*.json (arm/relation/conf).
Output: FP_LIST_FOR_E.md . Non-responses (null/skip) excluded. Authoritative FP count is from
bundle_meta; any FP whose text can't be recovered from HTML is listed as UNRESOLVED.
"""
import glob, json, re
from collections import defaultdict

HTML_ANN = ['poon', 'sharma', 'mu', 'xue', 'liu']

def extract_bundle(html):
    i = html.find('const BUNDLE ='); j = html.find('[', i)
    depth = 0; k = j; instr = False; esc = False
    while k < len(html):
        c = html[k]
        if esc: esc = False
        elif c == '\\': esc = True
        elif c == '"': instr = not instr
        elif not instr:
            if c == '[': depth += 1
            elif c == ']':
                depth -= 1
                if depth == 0: break
        k += 1
    return json.loads(html[j:k + 1])

meta = {}
for f in glob.glob('bundles/bundle_meta_*.json'):
    meta.update(json.load(open(f))['items'])

fp_by_rel = defaultdict(list)
n_auth = n_res = 0
for a in HTML_ANN:
    bundle = {b['shown_order']: b for b in extract_bundle(open(f'bundles/labeler_{a}.html').read())}
    for e in json.load(open(f'labels_{a}.json'))['labels']:
        m = meta.get(e['id'])
        if not m or m['arm'] != 'precision' or e['label'] != 'not_supported':
            continue
        n_auth += 1
        t = bundle.get(e['shown_order'])
        if t: n_res += 1
        fp_by_rel[m['relation']].append({
            'ann': a, 'conf': round(m['confidence'], 2), 'ooo': m['is_out_of_ontology'],
            'head': t.get('head', 'UNRESOLVED') if t else 'UNRESOLVED',
            'htype': t.get('head_type', '') if t else '',
            'tail': t.get('tail', 'UNRESOLVED') if t else '',
            'ttype': t.get('tail_type', '') if t else '',
            'quotes': (t.get('evidence_quotes', []) if t else [])[:3],
        })

out = ['# DIA False Positives — full annotated list (for improvement E)\n',
       f'DIA-approved edges (precision arm) that experts labelled `not_supported`. '
       f'Authoritative FP count = **{n_auth}** (from bundle_meta); text recovered for {n_res}/{n_auth} '
       f'via labeler HTML. Non-responses (null/skip) excluded. Generated by `build_fp_list.py`.\n',
       '## Design implications for improvement E\n',
       '1. **Mistyped tails defeat a naive type check.** Many `PERFORMS_FUNCTION` FP tails are device '
       'nouns (Light Source, Photodetector, Optical Switch, Power Splitter) that upstream PPC typing '
       'tagged as `Design_Function`, so the edge is schema-conformant. E must validate that the tail is a '
       '*genuine action/function*, not a device noun mistyped as one — or fix the typing upstream. A '
       'check that only asks "is tail Function-typed?" will pass these.\n',
       '2. **The true relation is usually containment/use, not function.** Evidence quotes for these FPs '
       'say "integrated with", "connected to", "consisted of" → `CONTAINS_/USES_COMPONENT`. E should '
       'prefer a structural relation when the quote is a composition statement.\n',
       '3. **Evidence is entity-pooled, not relation-specific** (root cause #3): several FPs carry quotes '
       'about unrelated topics (e.g. SiN-waveguide FPs quote cantilever beam-scanning). A relation-specific '
       'quote check at construction time would catch these.\n',
       '4. **Confidence does not separate FPs** (0.8–0.99, several at 0.98–0.99): thresholding will not '
       'filter them — the fix must be structural (typing + relation-specific evidence), not a cutoff.\n']
for rel in sorted(fp_by_rel, key=lambda r: -len(fp_by_rel[r])):
    rows = fp_by_rel[rel]
    out.append(f'\n## {rel} — {len(rows)} FP\n')
    for r in sorted(rows, key=lambda x: (x['ann'], -x['conf'])):
        out.append(f"- **{r['head']}** ({r['htype']}) --{rel}--> **{r['tail']}** ({r['ttype']})  "
                   f"· {r['ann']} · conf={r['conf']} · {'ooo' if r['ooo'] else 'in-onto'}")
        for q in r['quotes']:
            q = q.strip().replace('\n', ' ')
            out.append(f"    > {q[:240]}{'…' if len(q) > 240 else ''}")
open('FP_LIST_FOR_E.md', 'w').write('\n'.join(out) + '\n')
print(f'authoritative FP={n_auth}  resolved={n_res}  -> FP_LIST_FOR_E.md')
print('by relation:', {r: len(v) for r, v in sorted(fp_by_rel.items(), key=lambda x: -len(x[1]))})
